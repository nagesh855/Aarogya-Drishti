interface LocalizationContextValue {
  language: AppLanguage;
  setLanguage: (language: AppLanguage) => void;
}

const LocalizationContext = createContext<LocalizationContextValue>({
  language: 'en',
  setLanguage: () => undefined,
});

function readSavedLanguage(): AppLanguage {
  const saved = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
  return saved === 'te' || saved === 'hi' || saved === 'en' ? saved : 'en';
}

function isAppLanguage(value: string): value is AppLanguage {
  return value === 'te' || value === 'en' || value === 'hi';
}

function translate(value: string, language: AppLanguage): string {
  if (language === 'en') return value;
  return translations[language][value] || value;
}

function translatePreservingWhitespace(value: string, language: AppLanguage): string {
  const content = value.trim();
  if (!content) return value;
  const start = value.indexOf(content);
  return `${value.slice(0, start)}${translate(content, language)}${value.slice(
    start + content.length
  )}`;
}

function localizeTree(root: HTMLElement, language: AppLanguage): () => void {
  const textSources = new WeakMap<Text, { source: string; applied: string }>();
  const attributeSources = new WeakMap<Element, Map<string, { source: string; applied: string }>>();
  const textNodes = new Set<Text>();
  const attributes = ['aria-label', 'aria-description', 'title', 'placeholder', 'alt'];

  const localizeText = (node: Text) => {
    const parent = node.parentElement;
    if (
      !parent ||
      parent.closest('script, style, textarea, [contenteditable="true"], [data-no-translate]')
    ) {
      return;
    }

    const current = node.data;
    const previous = textSources.get(node);
    const source = previous && current === previous.applied ? previous.source : current;
    const localized = translatePreservingWhitespace(source, language);
    textSources.set(node, { source, applied: localized });
    textNodes.add(node);
    if (current !== localized) node.data = localized;
  };

  const localizeElement = (element: Element) => {
    let sources = attributeSources.get(element);
    if (!sources) {
      sources = new Map();
      attributeSources.set(element, sources);
    }
    for (const attribute of attributes) {
      const current = element.getAttribute(attribute);
      if (current === null) continue;
      const previous = sources.get(attribute);
      const source = previous && current === previous.applied ? previous.source : current;
      const localized = translatePreservingWhitespace(source, language);
      sources.set(attribute, { source, applied: localized });
      if (current !== localized) element.setAttribute(attribute, localized);
    }
  };

  const visit = (node: Node) => {
    if (node.nodeType === Node.TEXT_NODE) {
      localizeText(node as Text);
      return;
    }
    if (node.nodeType !== Node.ELEMENT_NODE && node.nodeType !== Node.DOCUMENT_FRAGMENT_NODE) {
      return;
    }
    if (node.nodeType === Node.ELEMENT_NODE) localizeElement(node as Element);
    const walker = document.createTreeWalker(node, NodeFilter.SHOW_ALL);
    let child = walker.nextNode();
    while (child) {
      if (child.nodeType === Node.TEXT_NODE) localizeText(child as Text);
      else if (child.nodeType === Node.ELEMENT_NODE) localizeElement(child as Element);
      child = walker.nextNode();
    }
  };

  visit(root);
  const observer = new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === 'characterData' && record.target.nodeType === Node.TEXT_NODE) {
        localizeText(record.target as Text);
      }
      for (const node of record.addedNodes) visit(node);
      if (record.type === 'attributes' && record.target.nodeType === Node.ELEMENT_NODE) {
        localizeElement(record.target as Element);
      }
    }
  });
  observer.observe(root, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: attributes,
  });

  return () => {
    observer.disconnect();
    for (const node of textNodes) {
      if (!node.isConnected) continue;
      const previous = textSources.get(node);
      if (previous && node.data === previous.applied) node.data = previous.source;
    }
    textNodes.clear();
  };
}

export function LocalizationProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>(readSavedLanguage);

  const setLanguage = (nextLanguage: AppLanguage) => {
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, nextLanguage);
    setLanguageState(nextLanguage);
  };

  useEffect(() => {
    document.documentElement.lang = language;
    const root = document.getElementById('root');
    if (!root) return;
    return localizeTree(root, language);
  }, [language]);

  const value = useMemo(() => ({ language, setLanguage }), [language]);
  return <LocalizationContext.Provider value={value}>{children}</LocalizationContext.Provider>;
}

export function useLocalization(): LocalizationContextValue {
  return useContext(LocalizationContext);
}

export function LanguageSelector({ className = '' }: { className?: string }) {
  const { language, setLanguage } = useLocalization();

  return (
    <label className={`inline-flex items-center gap-1.5 ${className}`}>
      <span className="sr-only">Language</span>
      <select
        aria-label="Choose application language"
        value={language}
        onChange={(event) => {
          if (isAppLanguage(event.currentTarget.value)) {
            setLanguage(event.currentTarget.value);
          }
        }}
        className="h-9 max-w-28 rounded-full border border-gray-200 bg-white px-3 text-xs font-semibold text-gray-700 shadow-sm outline-none transition-colors hover:border-teal-300 focus:border-teal-600 focus:ring-2 focus:ring-teal-100 cursor-pointer"
      >
        <option value="te">తెలుగు</option>
        <option value="en">English</option>
        <option value="hi">हिन्दी</option>
      </select>
    </label>
  );
}
